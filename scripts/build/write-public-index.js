#!/usr/bin/env node
"use strict";

// Canonical Venera source catalog. No duplicated hand-maintained metadata.
// Input: .generated/build-manifest.json#publicIndex (from plugin configs).
// Output: index.json, a standalone Venera-compatible JSON array.
const fs = require("node:fs");
const path = require("node:path");
const { REPO_ROOT, BUILD_MANIFEST_PATH, readJson } = require("./lib");

const TARGET = path.join(REPO_ROOT, "index.json");
const README_TARGET = path.join(REPO_ROOT, "CATALOG.md");

function buildPublicIndex(manifest) {
  if (!manifest || !Array.isArray(manifest.plugins) || !Array.isArray(manifest.publicIndex)) {
    throw new Error("Manifest must contain plugins and publicIndex arrays");
  }
  const known = new Map();
  for (const plugin of manifest.plugins) {
    if (!plugin || typeof plugin.id !== "string" || known.has(plugin.id)) {
      throw new Error("Missing or duplicate plugin identity in manifest");
    }
    known.set(plugin.id, plugin);
  }
  if (known.size !== manifest.publicIndex.length || known.size === 0) {
    throw new Error("Public index must match all canonical plugin configs");
  }
  const seen = new Set();
  for (const entry of manifest.publicIndex) {
    if (!entry || typeof entry !== "object" || Array.isArray(entry)) {
      throw new Error("Invalid public index entry");
    }
    const plugin = known.get(entry.key);
    if (!plugin || seen.has(entry.key)) throw new Error("Unknown/duplicate public index key");
    seen.add(entry.key);
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(entry.key) ||
        typeof entry.name !== "string" || !entry.name.trim() ||
        !/^[0-9]+\.[0-9]+\.[0-9]+(?:[-+][A-Za-z0-9.-]+)?$/.test(entry.version) ||
        typeof entry.fileName !== "string" || !/^[A-Za-z0-9_-]+\.js$/.test(entry.fileName) ||
        typeof entry.url !== "string" || !entry.url.startsWith("https://") ||
        entry.fileName !== plugin.artifact ||
        entry.version !== plugin.version || entry.name !== plugin.name ||
        entry.url !== plugin.publicUrl) {
      throw new Error("Public index entry disagrees with canonical manifest: " + entry.key);
    }
  }
  return JSON.stringify(manifest.publicIndex, null, 2) + "\n";
}

function buildCatalogReadme(manifest) {
  // Force integrity validation before publishing generated prose.
  buildPublicIndex(manifest);
  const tick = String.fromCharCode(96);
  const text = value => String(value).replace(/[|<>\r\n]/g, " ").replace(/[\[\]]/g, "");
  const rows = [
    "<!-- GENERATED by npm run build:index. DO NOT EDIT. -->",
    "# Canonical Venera Source Catalog",
    "",
    "This source list is generated from the canonical " + tick +
      ".generated/build-manifest.json#publicIndex" + tick + ".",
    "Import the actual Venera-compatible JSON array using [index.json](index.json) " +
      "via a raw HTTP(S) URL. This is not a runtime loader.",
    "",
    "| Source | Key | Version | Artifact |",
    "| --- | --- | --- | --- |",
    ...manifest.publicIndex.map(p =>
      "| " + text(p.name) + " | " + tick + text(p.key) + tick + " | " +
      text(p.version) + " | [" + text(p.fileName) + "](dist/plugins/" +
      p.fileName + ") |"),
    "",
    "Total canonical sources: **" + manifest.publicIndex.length + "**.",
    "",
    "## Generate and verify",
    "",
    tick + tick + tick + "bash",
    "npm run pipeline:build",
    "npm run build:index",
    "npm run check:index-json",
    tick + tick + tick,
    "",
    "This file and " + tick + "index.json" + tick +
      " are generated. Edit " + tick + "plugins/*/plugin.config.json" + tick +
      " and source files instead. Experimental legacy JS sources are listed " +
      "separately in [the experimental index](experiments/legacy-comic-sources/INDEX.md).",
    "",
    "See [the index build guide](docs/index-build.md) and [the main README](README.md).",
    "",
  ];
  return rows.join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const manifest = readJson(BUILD_MANIFEST_PATH);
  const targets = [
    [TARGET, buildPublicIndex(manifest)],
    [README_TARGET, buildCatalogReadme(manifest)],
  ];
  for (const [file, expected] of targets) {
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== expected) {
        throw new Error(path.basename(file) + " drift: run npm run build:index");
      }
    } else {
      fs.writeFileSync(file, expected, "utf8");
    }
  }
  console.log(check ? "Canonical index.json and CATALOG.md are up to date" :
    "Generated canonical index.json and CATALOG.md");
}

if (require.main === module) main();

module.exports = { buildPublicIndex, buildCatalogReadme };
