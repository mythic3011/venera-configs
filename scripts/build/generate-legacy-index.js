#!/usr/bin/env node
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "../..");
const DIR = path.join(ROOT, "experiments", "legacy-comic-sources");
const MANIFEST = path.join(DIR, "catalog.sources.json");

function safeText(value, label) {
  if (typeof value !== "string" || !value.trim() ||
      value.length > 400 || /[\r\n|<>]/.test(value)) {
    throw new Error("Invalid catalog " + label);
  }
  return value;
}

function parseClassMetadata(source) {
  const match = /\bclass\s+[A-Za-z_$][\w$]*\s+extends\s+ComicSource\s*\{/.exec(source);
  if (!match || match.index > 1200) throw new Error("Expected standalone ComicSource class");
  // Static identity fields must appear before any runtime settings or method.
  const prefix = source.slice(match.index + match[0].length, match.index + match[0].length + 450);
  const meta = {};
  for (const field of ["name", "key", "version", "minAppVersion"]) {
    const m = new RegExp("^\\s*" + field + "\\s*=\\s*\"([^\"]+)\"\\s*;", "m").exec(prefix);
    if (!m) throw new Error("Missing static identity field: " + field);
    meta[field] = m[1];
  }
  return meta;
}

function buildLegacyIndex(entries, readSource) {
  if (!Array.isArray(entries) || entries.length === 0 || entries.length > 32) {
    throw new Error("Legacy catalog must be a bounded nonempty array");
  }
  if (typeof readSource !== "function") throw new TypeError("readSource required");
  const seenKeys = new Set();
  const seenFiles = new Set();
  const allowedFields = ["name", "key", "version", "minAppVersion", "fileName", "description", "status"];
  const records = entries.map(item => {
    if (!item || typeof item !== "object" || Array.isArray(item) ||
        Object.keys(item).some(key => !allowedFields.includes(key))) {
      throw new Error("Unknown catalog fields");
    }
    const key = safeText(item.key, "key");
    const name = safeText(item.name, "name");
    const version = safeText(item.version, "version");
    const minAppVersion = safeText(item.minAppVersion, "minAppVersion");
    const fileName = safeText(item.fileName, "fileName");
    const description = safeText(item.description, "description");
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) ||
        !/^[A-Za-z0-9_-]+\.js$/.test(fileName) ||
        !/^\d+\.\d+\.\d+$/.test(version) ||
        !/^\d+\.\d+\.\d+$/.test(minAppVersion) ||
        item.status !== "experimental") {
      throw new Error("Invalid legacy source identity, file, version or status");
    }
    if (seenKeys.has(key) || seenFiles.has(fileName)) {
      throw new Error("Duplicate legacy source key or file");
    }
    seenKeys.add(key);
    seenFiles.add(fileName);
    const code = readSource(fileName);
    if (typeof code !== "string") throw new Error("Missing script " + fileName);
    const fields = parseClassMetadata(code);
    for (const field of ["name", "key", "version", "minAppVersion"]) {
      if (fields[field] !== item[field]) {
        throw new Error("Catalog/script " + field + " mismatch for " + key);
      }
    }
    return { name, key, version, minAppVersion, fileName, description };
  });
  records.sort((a, b) => a.key < b.key ? -1 : a.key > b.key ? 1 : 0);
  const index = records.map(({name, key, version, fileName, description}) =>
    ({name, key, version, fileName, description}));
  const tick = String.fromCharCode(96);
  const lines = [
    "<!-- AUTO-GENERATED by npm run build:legacy-index. DO NOT EDIT. -->",
    "# Experimental Venera JS Source Index",
    "",
    "This README is generated from " + tick + "catalog.sources.json" + tick +
      ". It is a **temporary, non-canonical catalog** for manual legacy JS imports.",
    "",
    "| Source | Key | Version | Min Venera | Status |",
    "| --- | --- | --- | --- | --- |",
    ...records.map(r =>
      "| [" + r.name + "](" + r.fileName + ") | " + tick + r.key + tick +
      " | " + r.version + " | " + r.minAppVersion + " | Experimental |"),
    "",
    "## Install the JSON index",
    "",
    "Open this directory's " + tick + "index.json" + tick + " via a **raw HTTP(S) URL** " +
      "(not a GitHub HTML blob page), then import that address in a Venera build supporting " +
      "the source repository JSON-array interface. Relative " + tick + "fileName" + tick +
      " entries resolve from the final JSON response URL.",
    "",
    "The parent [README](README.md) documents settings, API key risks, host-level LAN grants, " +
      "limitations and troubleshooting. The official catalog is the repository-root " + tick +
      "index.json" + tick + ". Importing this experimental index does not install or replace " +
      "the existing canonical LANraragi plugin.",
    "",
    "## Rebuild",
    "",
    tick + tick + tick + "bash",
    "npm run build:legacy-index",
    "npm run check:legacy-index",
    tick + tick + tick,
    "",
    "Do not edit " + tick + "index.json" + tick + " or this generated file by hand. " +
      "Edit " + tick + "catalog.sources.json" + tick + " and the corresponding JavaScript source.",
    "",
    "No release publishing, credentials, or backup/snapshot guarantees are provided.",
    "",
  ];
  return {
    indexJson: JSON.stringify(index, null, 2) + "\n",
    indexReadme: lines.join("\n"),
  };
}

function main() {
  const check = process.argv.includes("--check");
  const entries = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  const output = buildLegacyIndex(entries, name =>
    fs.readFileSync(path.join(DIR, name), "utf8"));
  const files = [["index.json", output.indexJson], ["INDEX.md", output.indexReadme]];
  for (const [name, expected] of files) {
    const target = path.join(DIR, name);
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== expected) {
        throw new Error("Generated " + name + " is stale: npm run build:legacy-index");
      }
    } else {
      fs.writeFileSync(target, expected, "utf8");
    }
  }
  console.log(check ? "Experimental JSON index and INDEX.md match sources" :
    "Generated experimental index.json and INDEX.md");
}

if (require.main === module) main();
module.exports = { buildLegacyIndex, parseClassMetadata };
